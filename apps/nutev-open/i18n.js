  var current = "pt";

  function format(template, vars) {
    return String(template).replace(/\{(\w+)\}/g, function (match, key) {
      return vars && vars[key] !== undefined && vars[key] !== null ? String(vars[key]) : match;
    });
  }

  function t(key, vars) {
    var table = STRINGS[current] || STRINGS.pt;
    var value = table[key];
    if (value === undefined) value = STRINGS.pt[key];
    if (value === undefined) return key;
    return format(value, vars);
  }

  function setLang(lang) {
    current = STRINGS[lang] ? lang : "pt";
    if (typeof document !== "undefined") {
      document.documentElement.lang = current === "pt" ? "pt-BR" : "en";
    }
    return current;
  }

  function lang() {
    return current;
  }

  /** Apply data-i18n (text) and data-i18n-placeholder / data-i18n-aria attributes. */
  function apply(scope) {
    var rootNode = scope || document;
    rootNode.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = t(node.getAttribute("data-i18n"));
    });
    rootNode.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
      node.setAttribute("placeholder", t(node.getAttribute("data-i18n-placeholder")));
    });
    rootNode.querySelectorAll("[data-i18n-aria]").forEach(function (node) {
      node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria")));
    });
  }

